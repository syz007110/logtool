const router = require('express').Router();
const auth = require('../middlewares/auth');
const { checkPermission } = require('../middlewares/permission');
const controller = require('../controllers/roleController');
router.get('/', auth, checkPermission('role:read'), controller.getRoles);
router.post('/', auth, checkPermission('role:manage'), controller.createRole);
router.get('/:id', auth, checkPermission('role:read'), controller.getRole);
router.patch('/:id', auth, checkPermission('role:manage'), controller.updateRole);
router.delete('/:id', auth, checkPermission('role:manage'), controller.deleteRole);
module.exports = router;
